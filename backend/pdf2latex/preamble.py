"""
preamble.py — Deterministic shared preamble and document assembly.

The preamble comes from the extracted facts only: article class, geometry matching
the page size and content margins, xcolor with one \\definecolor per distinct RGB
found (exact values), graphicx, amsmath/amssymb and the closest pdfLaTeX font
packages for the PDF's fonts. Page bodies (from the LLM or the layout fallback) are
merged under it, separated by \\newpage.
"""

import re
from collections import Counter
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Sequence

from .models import RGB, DocExtract, PageExtract, StyleProfile
from .texutil import fmt

PAGE_MARK = "%% ==== OB-PAGE {n} ===="
_PAGE_MARK_RE = re.compile(r"^%% ==== OB-PAGE (\d+) ====$", re.MULTILINE)
_INCLUDE_RE = re.compile(r"\\includegraphics\s*(?:\[[^\]]*\])?\s*\{([^}]+)\}")
MAX_MARGIN = 144.0


@dataclass(frozen=True)
class Geometry:
    paper_w: float
    paper_h: float
    left: float
    top: float
    right: float
    bottom: float

    @property
    def text_w(self) -> float:
        return self.paper_w - self.left - self.right

    @property
    def text_h(self) -> float:
        return self.paper_h - self.top - self.bottom


@dataclass(frozen=True)
class FontPlan:
    main: str  # "times" | "palatino" | "lmodern" | "helvetica" | "courier" | "carlito" | "caladea"
    main_family: str  # "serif" | "sans" | "mono"
    uses_sans: bool
    uses_mono: bool
    body_size: float
    sans: str = "helvetica"  # font class providing \sffamily when sans is secondary


def page_geometry(doc: DocExtract) -> Geometry:
    """Most common page size; each margin is the smallest content margin over all pages."""
    sizes = Counter((round(p.width, 1), round(p.height, 1)) for p in doc.pages)
    paper_w, paper_h = sizes.most_common(1)[0][0]
    with_content = [p for p in doc.pages if p.lines or p.images or p.drawings] or doc.pages
    m = [min(p.margins[i] for p in with_content) for i in range(4)]
    left, top, right, bottom = (max(0.0, min(v, MAX_MARGIN) - 1.0) for v in m)
    if paper_w - left - right < 0.3 * paper_w or paper_h - top - bottom < 0.3 * paper_h:
        left = top = right = bottom = 36.0
    return Geometry(paper_w, paper_h, left, top, right, bottom)


def color_name(rgb: RGB) -> str:
    return "c%02X%02X%02X" % tuple(int(v) for v in rgb)


def collect_colors(doc: DocExtract) -> Dict[str, RGB]:
    """Every distinct text / rule / fill color, most used first; black is always defined."""
    counts: Counter = Counter()
    for p in doc.pages:
        for ln in p.lines:
            for sp in ln.spans:
                counts[sp.color] += max(1, len(sp.text.strip()))
        for d in p.drawings:
            for c in (d.stroke, d.fill):
                if c is not None:
                    counts[c] += 1
    counts[(0, 0, 0)] += 0
    return {color_name(rgb): rgb for rgb, _ in counts.most_common()}


# Font classification lives in fontmap.py (metric-compatible substitutes, weights).
from .fontmap import FONT_LINES, SECONDARY_LINES, family_of, font_class  # noqa: E402,F401


def plan_fonts(doc: DocExtract) -> FontPlan:
    by_class: Counter = Counter()
    by_size: Counter = Counter()
    for p in doc.pages:
        for ln in p.lines:
            for sp in ln.spans:
                n = len(sp.text.strip())
                if n:
                    by_class[font_class(sp.font, sp.flags)] += n
                    by_size[round(sp.size * 2) / 2] += n
    main = by_class.most_common(1)[0][0] if by_class else "lmodern"
    families = {family_of(c) for c in by_class}
    main_family = family_of(main)
    sans_classes = [c for c, _ in by_class.most_common() if family_of(c) == "sans" and c in SECONDARY_LINES]
    return FontPlan(
        main=main,
        main_family=main_family,
        uses_sans="sans" in families and main_family != "sans",
        uses_mono="mono" in families and main_family != "mono",
        body_size=float(by_size.most_common(1)[0][0]) if by_size else 10.0,
        sans=sans_classes[0] if sans_classes else "helvetica",
    )


def build_preamble(geom: Geometry, colors: Dict[str, RGB], fonts: FontPlan,
                   profile: Optional[StyleProfile] = None) -> str:
    """
    The shared preamble. With ``profile`` (template mode, M13) the margins are given in mm
    and a commented block of semantic style commands follows the colors; without it the
    output is exactly the exact-mode preamble.
    """
    lines = [
        "% Generated by OverBranch PDF import (best-effort reproduction; compile with pdfLaTeX).",
        "\\documentclass{article}",
        "\\usepackage[T1]{fontenc}",
        "\\usepackage[utf8]{inputenc}",
        "\\usepackage{textcomp}",
        *FONT_LINES[fonts.main],
    ]
    if fonts.uses_sans:
        lines.append(SECONDARY_LINES.get(fonts.sans, SECONDARY_LINES["helvetica"]))
    if fonts.uses_mono:
        lines.append("\\usepackage{courier}")
    if profile is None:
        geometry = (f"\\usepackage[paperwidth={fmt(geom.paper_w)}bp,paperheight={fmt(geom.paper_h)}bp,"
                    f"left={fmt(geom.left)}bp,right={fmt(geom.right)}bp,top={fmt(geom.top)}bp,"
                    f"bottom={fmt(geom.bottom)}bp]{{geometry}}")
    else:
        geometry = _template_geometry_lines(geom, profile)
    lines += [
        geometry,
        "\\usepackage[table]{xcolor}",
        "\\usepackage{graphicx}",
        "\\usepackage{amsmath,amssymb}",
        "\\usepackage{array,tabularx,booktabs,multirow}",
        "\\usepackage{multicol}",
        "\\usepackage{enumitem}",
        "\\usepackage{ragged2e}",
        "\\usepackage{tikz}",
        "\\usepackage{eso-pic}",
        "\\usepackage{url}",
    ]
    lines += [f"\\definecolor{{{name}}}{{RGB}}{{{r},{g},{b}}}" for name, (r, g, b) in colors.items()]
    if profile is not None:
        lines += style_block(profile)
    size, lead = fmt(fonts.body_size), fmt(fonts.body_size * 1.2)
    lines += [
        "\\pagestyle{empty}",
        "\\setlength{\\parindent}{0pt}",
        "\\setlength{\\parskip}{0pt}",
        "\\setlength{\\topskip}{0pt}",
        "\\setlength{\\emergencystretch}{2em}",
        "\\raggedbottom",
        # Shrinks a page body that would spill onto a second page (overflow fallback)
        "\\newsavebox{\\obpagebox}",
        "\\newcommand{\\obfit}[1]{\\sbox{\\obpagebox}{\\begin{minipage}[t]{\\linewidth}#1\\end{minipage}}%",
        "  \\ifdim\\dimexpr\\ht\\obpagebox+\\dp\\obpagebox\\relax>\\dimexpr\\textheight-2pt\\relax"
        "\\resizebox*{!}{\\dimexpr\\textheight-2pt\\relax}{\\usebox{\\obpagebox}}\\else\\usebox{\\obpagebox}\\fi}",
        # Condenses one line horizontally to a width, only if it is wider (right-edge fit)
        "\\newsavebox{\\obhbox}",
        "\\newcommand{\\obhfit}[2]{\\sbox{\\obhbox}{#2}%",
        "  \\ifdim\\wd\\obhbox>#1\\relax\\resizebox{#1}{\\ht\\obhbox}{\\usebox{\\obhbox}}\\else\\usebox{\\obhbox}\\fi}",
        f"\\AtBeginDocument{{\\fontsize{{{size}bp}}{{{lead}bp}}\\selectfont}}" if profile is None
        else "\\AtBeginDocument{\\obBodyFont}",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Template mode (M13 / M14): the document's style as editable semantic commands
# ---------------------------------------------------------------------------

MM_PER_BP = 25.4 / 72.0
SINGLE_SPACING = 1.2       # baseline distance of "single" spacing, as a multiple of the font size
HEADING_NAMES = ("H1", "H2", "H3")
HEADING_COMMANDS = {"H1": "obHeadingI", "H2": "obHeadingII", "H3": "obHeadingIII"}
MAX_PARAGRAPH_LEAD = 2.6   # a baseline step above this many body sizes is a paragraph break, not leading
_FAMILY_SWITCH = {"serif": "\\rmfamily", "sans": "\\sffamily", "mono": "\\ttfamily"}
_MARGIN_KEYS = ("top", "bottom", "left", "right")
_HEX_RE = re.compile(r"^#?([0-9a-fA-F]{6})$")


def _half(v: float) -> float:
    return round(v * 2) / 2


def _hex(rgb: RGB) -> str:
    return "#%02x%02x%02x" % tuple(int(v) for v in rgb)


def hex_to_rgb(value: str) -> Optional[RGB]:
    m = _HEX_RE.match((value or "").strip())
    if not m:
        return None
    h = m.group(1)
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def _family(font: str) -> str:
    return family_of(font_class(font)) if font else "serif"


ROLE_COMMANDS = {"body": "obBodyFont", **HEADING_COMMANDS}


@dataclass(frozen=True)
class StyleMatch:
    """
    A run set with a semantic style command plus only the modifiers where it differs from
    that style's own definition (template mode). ``None`` for a modifier means "as the style".

    - role: "body" or "H1".."H3";
    - bold / italic: True → \\bfseries / \\itshape, False → \\mdseries / \\upshape;
    - color: a preamble colour name (``color_name``) applied with \\textcolor.
    """
    role: str
    bold: Optional[bool] = None
    italic: Optional[bool] = None
    color: Optional[str] = None

    @property
    def command(self) -> str:
        return "\\" + ROLE_COMMANDS[self.role]

    @property
    def plain(self) -> bool:
        """True when the run is exactly the style: the bare command, as before modifiers existed."""
        return self.bold is None and self.italic is None and self.color is None

    def font(self) -> str:
        """The command and the weight / slant modifiers (a font switch, usable as TikZ ``font=``)."""
        out = self.command
        if self.bold is not None:
            out += "\\bfseries" if self.bold else "\\mdseries"
        if self.italic is not None:
            out += "\\itshape" if self.italic else "\\upshape"
        return out

    def wrap(self, text: str) -> str:
        """``text`` in the colour modifier, when there is one."""
        return f"\\textcolor{{{self.color}}}{{{text}}}" if self.color else text

    def latex(self, text: str) -> str:
        """The whole run as a group, e.g. ``{\\obBodyFont\\bfseries\\textcolor{c0000FF}{text}}``."""
        return "{" + self.font() + self.wrap(text) + "}"


def style_role(profile: Optional[StyleProfile], size: float, bold: bool, italic: bool, family: str,
               color: str, default_color: str) -> Optional[StyleMatch]:
    """
    The document style a run (size in pt, color as a preamble color name) is set in, so it uses
    the semantic command instead of inline formatting. Size (within 0.5pt) and family decide the
    style; weight, slant and colour that differ from the style's definition become modifiers
    on the match. When several styles share the size and family (a regular body and a bold
    heading at 12pt) the one needing the fewest modifiers wins, the body first on a tie.
    None only when the size or family differs from every style: a genuine one-off span.
    """
    if profile is None:
        return None
    # (role, size, bold, italic, family, colour name) of each style, as the preamble defines it.
    styles = [("body", profile.body_size_pt, False, False, _family(profile.body_font), default_color)]
    for h in profile.heading_levels:
        styles.append((h.name, h.size_pt, h.bold, h.italic, _family(h.font),
                       color_name(hex_to_rgb(h.color) or (0, 0, 0))))
    best: Optional[StyleMatch] = None
    best_cost = 4
    for role, s_size, s_bold, s_italic, s_family, s_color in styles:
        if abs(size - s_size) >= 0.5 or family != s_family:
            continue
        match = StyleMatch(role=role,
                           bold=bool(bold) if bool(bold) != s_bold else None,
                           italic=bool(italic) if bool(italic) != s_italic else None,
                           color=color if color != s_color else None)
        cost = sum(v is not None for v in (match.bold, match.italic, match.color))
        if cost < best_cost:
            best, best_cost = match, cost
    return best


def _origin(profile: StyleProfile, key: str) -> str:
    return "stated in the document" if key in profile.stated_fields else "measured from the PDF"


def _font_switch(font: str, size: float, lead: float, bold: bool, italic: bool) -> str:
    return (f"\\fontsize{{{fmt(size)}bp}}{{{fmt(size * lead)}bp}}\\selectfont{_FAMILY_SWITCH[_family(font)]}"
            + ("\\bfseries" if bold else "\\mdseries") + ("\\itshape" if italic else "\\upshape"))


def _comment(text: str) -> str:
    return "% " + " ".join(str(text).split())


def _template_geometry_lines(geom: Geometry, profile: StyleProfile) -> str:
    m = profile.margins_mm
    origins = sorted({_origin(profile, f"margins_mm.{k}") for k in _MARGIN_KEYS})
    return "\n".join([
        _comment(f"Margins: top {fmt(m['top'])}mm, bottom {fmt(m['bottom'])}mm, left {fmt(m['left'])}mm, "
                 f"right {fmt(m['right'])}mm ({' / '.join(origins)}). Change them here."),
        f"\\usepackage[paperwidth={fmt(geom.paper_w)}bp,paperheight={fmt(geom.paper_h)}bp,"
        f"top={fmt(m['top'])}mm,bottom={fmt(m['bottom'])}mm,left={fmt(m['left'])}mm,right={fmt(m['right'])}mm]{{geometry}}",
    ])


def accent_color(profile: StyleProfile) -> str:
    """The most used color that is neither black nor white (black when there is none)."""
    for c in profile.colors:
        rgb = hex_to_rgb(c)
        if rgb and rgb not in ((0, 0, 0), (255, 255, 255)):
            return _hex(rgb)
    return "#000000"


def style_block(profile: StyleProfile) -> List[str]:
    """The commented, semantic style definitions (template mode). One comment per definition."""
    by_name = {h.name: h for h in profile.heading_levels}
    out = [
        "% ---- Document style (template mode) ----",
        "% Edit these definitions to restyle the whole document: the page bodies use them",
        "% instead of setting body and heading fonts, sizes and colours inline.",
        _comment(f"Body text: {profile.body_font or 'default font'} {fmt(profile.body_size_pt)}pt "
                 f"({' / '.join(sorted({_origin(profile, 'body_font'), _origin(profile, 'body_size_pt')}))}); "
                 f"line spacing {fmt(profile.line_spacing, 3)} x the size ({_origin(profile, 'line_spacing')})."),
        f"\\newcommand{{\\obBodyFont}}{{{_font_switch(profile.body_font, profile.body_size_pt, profile.line_spacing, False, False)}}}",
    ]
    for level, name in enumerate(HEADING_NAMES, start=1):
        cmd = HEADING_COMMANDS[name]
        h = by_name.get(name)
        if h is None:
            out += [_comment(f"Heading level {level}: not found in the PDF; defaults to bold body text."),
                    f"\\newcommand{{\\{cmd}}}{{\\obBodyFont\\bfseries}}"]
            continue
        rgb = hex_to_rgb(h.color) or (0, 0, 0)
        weight = ", ".join(w for w, on in (("bold", h.bold), ("italic", h.italic)) if on) or "regular"
        out += [
            _comment(f"Heading level {level}: {h.font or 'default font'} {fmt(h.size_pt)}pt {weight} {_hex(rgb)}, "
                     f"about {fmt(h.spacing_before_pt, 1)}pt of space before it ({_origin(profile, name)})."),
            f"\\newcommand{{\\{cmd}}}{{{_font_switch(h.font, h.size_pt, SINGLE_SPACING, h.bold, h.italic)}"
            f"\\color[HTML]{{{'%02X%02X%02X' % rgb}}}}}",
        ]
    accent = accent_color(profile)
    out += [
        _comment(f"Accent colour: {accent}, the most used colour other than black and white (measured from the PDF)."),
        f"\\definecolor{{obAccent}}{{HTML}}{{{accent[1:].upper()}}}",
        "\\newcommand{\\obAccentColor}{\\color{obAccent}}",
        "% ---- end of document style ----",
    ]
    return out


def background_command(file: str) -> str:
    return ("\\AddToShipoutPictureBG*{\\AtPageLowerLeft{\\includegraphics[width=\\paperwidth,"
            f"height=\\paperheight]{{{file}}}}}}}")


_STRIP_LINE_RE = re.compile(r"^\s*\\(documentclass|usepackage|RequirePackage|usetikzlibrary)\b.*$", re.MULTILINE)
_EDGE_BREAK_RE = re.compile(r"^(\s*\\(newpage|clearpage|pagebreak)\b(\[[^\]]*\])?\s*)+|(\s*\\(newpage|clearpage|pagebreak)\b(\[[^\]]*\])?\s*)+$")


def clean_body(text: str) -> str:
    """Keeps only body LaTeX: drops fences, commentary around a fenced block, preamble lines and edge page breaks."""
    b = (text or "").strip()
    fenced = re.search(r"```[a-zA-Z]*\s*\n(.*?)```", b, re.DOTALL)
    if fenced:
        b = fenced.group(1)
    if "\\begin{document}" in b:
        b = b.split("\\begin{document}", 1)[1]
    if "\\end{document}" in b:
        b = b.split("\\end{document}", 1)[0]
    b = _STRIP_LINE_RE.sub("", b)
    prev = None
    while prev != b:
        prev = b
        b = _EDGE_BREAK_RE.sub("", b.strip())
    return b.strip()


def assemble_document(preamble: str, bodies: Dict[int, str]) -> str:
    empty = "\\null"  # keeps an empty page as a page
    parts = [PAGE_MARK.format(n=n) + "\n" + (bodies[n].strip() or empty) for n in sorted(bodies)]
    return preamble + "\n\\begin{document}\n" + "\n\\newpage\n".join(parts) + "\n\\end{document}\n"


def standalone_page(preamble: str, body: str, n: int) -> str:
    return assemble_document(preamble, {n: body})


def page_for_line(tex: str, line_no: int) -> Optional[int]:
    """1-based source line → page number of the OB-PAGE block containing it."""
    page = None
    for i, line in enumerate(tex.splitlines(), start=1):
        if i > line_no:
            break
        m = _PAGE_MARK_RE.match(line)
        if m:
            page = int(m.group(1))
    return page


def body_of(tex: str, n: int) -> Optional[str]:
    """Extracts page n's body from an assembled document."""
    m = re.search(re.escape(PAGE_MARK.format(n=n)) + r"\n(.*?)(?=\n\\newpage\n%% ==== OB-PAGE |\n\\end\{document\})",
                  tex, re.DOTALL)
    return m.group(1) if m else None


def referenced_files(body: str) -> List[str]:
    return sorted({m.group(1).strip() for m in _INCLUDE_RE.finditer(body)})
